"""GitHub search node.
Executes the sub‑queries generated by the planner using the GitHubClient.
Results are stored in `state.raw_github`.
Any API errors are recorded in `state.limitations` and do not abort the graph.
"""

from typing import List

from ..state import ResearchState
from ...tools.github_client import GitHubClient, GitHubRepo
from ...shared.schemas.research import Limitation

async def github_search(state: ResearchState) -> ResearchState:
    plan = state.plan or {}
    queries: List[str] = plan.get("github", [])
    client = GitHubClient()
    all_results: List[GitHubRepo] = []
    for q in queries:
        try:
            repos = await client.search_repos(q, limit=5)
            all_results.extend(repos)
        except Exception as exc:
            state.limitations.append(
                Limitation(source="github", message=f"GitHub search failed for '{q}': {exc}")
            )
    state.raw_github = all_results
    return state
