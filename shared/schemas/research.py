'''Shared schemas for the Research Agent module.
These models are the source of truth for the public API and must match the
contract defined in `TEAM_INTEGRATION_SPEC.md`.
'''

from __future__ import annotations

from typing import List, Optional, Literal
from datetime import datetime
from pydantic import BaseModel, Field, HttpUrl, validator

from ..enums import ResearchStatus


class SourceType(str):
    """Allowed source identifiers.
    The enum values are defined in the contract; keeping them as literals makes
    validation straightforward without a separate Enum class which would add a
    dependency on the shared package.
    """

    GITHUB = "github"
    PAPER = "paper"
    WEB = "web"
    WIKIPEDIA = "wikipedia"


class EvidenceItem(BaseModel):
    """Canonical representation of a single piece of evidence.
    Every provider must be normalized into this shape before ranking or
    synthesis.
    """

    id: str = Field(..., description="Unique identifier within the research run.")
    source: Literal["github", "paper", "web", "wikipedia"] = Field(..., description="Origin of the evidence.")
    title: str = Field(..., description="Title or name of the item.")
    url: HttpUrl = Field(..., description="Permanent URL to the source material.")
    snippet: Optional[str] = Field(None, description="Short excerpt or abstract.")
    metadata: dict = Field(default_factory=dict, description="Provider‑specific data (e.g., stars, citations).")
    relevance_score: Optional[float] = Field(
        None, ge=0.0, le=1.0, description="Score (0‑1) assigned during ranking.")

    @validator("relevance_score", pre=True, always=True)
    def default_score(cls, v):
        return v if v is not None else 0.0


class Limitation(BaseModel):
    """Recorded limitation or failure encountered during the research run.
    This is surfaced to the user under a dedicated "limitations" field.
    """

    source: Literal["github", "paper", "web", "wikipedia"] = Field(...)
    message: str = Field(..., description="Human‑readable description of the issue.")


class ResearchRequest(BaseModel):
    """Input contract for the Research Agent.
    Mirrors the JSON payload accepted by the FastAPI endpoint.
    """

    session_id: str = Field(..., description="Caller‑provided identifier for tracing.")
    query: str = Field(..., description="User's natural‑language research question.")
    source_types: List[Literal["github", "paper", "web", "wikipedia"]] = Field(
        default_factory=lambda: ["github", "paper", "web"],
        description="Ordered list of sources to query.")
    max_sources: int = Field(15, ge=1, le=50, description="Maximum total evidence items to return.")
    user_constraints: List[str] = Field(default_factory=list, description="Optional constraints supplied by the user.")

    @validator("source_types", each_item=True)
    def check_source(cls, v):
        return v


class ResearchResult(BaseModel):
    """Output contract returned by `run_research`.
    All fields are required; optional collections use empty lists.
    """

    session_id: str = Field(...)
    query: str = Field(...)
    status: Literal["completed", "failed"] = Field(..., description="Overall status of the run.")
    created_at: datetime = Field(default_factory=datetime.utcnow)
    completed_at: Optional[datetime] = Field(None)
    summary: Optional[str] = Field(None, description="High‑level answer generated by the synthesizer.")
    key_findings: List[str] = Field(default_factory=list)
    recommendations: List[str] = Field(default_factory=list)
    evidence: List[EvidenceItem] = Field(default_factory=list)
    limitations: List[Limitation] = Field(default_factory=list)

    @validator("completed_at", always=True)
    def set_completed(cls, v, values):
        if v is None and values.get("status") == "completed":
            return datetime.utcnow()
        return v
